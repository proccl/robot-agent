        '    fprintf(fid, ''current_q: %%s\\n'', mat2str(fig.UserData.current_q));\n' ...
        '    fprintf(fid, ''target_pos: %%s\\n'', mat2str(T_target(1:3,4)''));\n' ...
        '    fprintf(fid, ''failed_step: %%d\\n'', first_nan);\n' ...
        '    fprintf(fid, ''total_steps: %%d\\n'', steps);\n' ...
        '    fprintf(fid, ''cmd: move_to\\n'');\n' ...
        '    fclose(fid);\n' ...
        '    fprintf(''[PAUSE] IK unreachable at step %%d/%%d. State saved to %%s\\n'', first_nan, steps, pause_path);\n' ...
