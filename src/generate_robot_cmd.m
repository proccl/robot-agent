function filepath = generate_robot_cmd(cmd_struct, output_dir)
% generate_robot_cmd 根據結構化指令生成可執行 .m 文件
%   cmd_struct: struct，必須包含 'cmd' 字段
%   output_dir: 輸出目錄，默認為 'incoming/'
%   filepath: 生成的文件路徑

    if nargin < 2 || isempty(output_dir)
        scriptDir = fileparts(mfilename('fullpath'));
        output_dir = fullfile(scriptDir, '..', 'incoming');
    end
    if ~exist(output_dir, 'dir')
        mkdir(output_dir);
    end
    
    timestamp = datestr(now, 'yyyymmdd_HHMMSS_FFF');
    filename = sprintf('cmd_%s_%s.m', timestamp, cmd_struct.cmd);
    filepath = fullfile(output_dir, filename);
    
    code = buildCode(cmd_struct);
    
    fid = fopen(filepath, 'w');
    fwrite(fid, code);
    fclose(fid);
end

%% ===== 內部函數：代碼構建 =====

function code = buildCode(cmd)
    if ~isstruct(cmd) || ~isfield(cmd, 'cmd')
        code = 'error(''Invalid command structure'');';
        return;
    end
    
    % 默認 duration
    if isfield(cmd, 'duration') && ~isempty(cmd.duration)
        duration = cmd.duration;
    else
        duration = 5;
    end
    
    switch cmd.cmd
        case 'home'
            code = buildHomeCode(duration);
        case 'move_to'
            code = buildMoveToCode(cmd, duration);
        case 'joint_move'
            code = buildJointMoveCode(cmd, duration);
        case 'trajectory'
            code = buildTrajectoryCode(cmd, duration);
        case 'get_status'
            code = buildGetStatusCode();
        case 'relative_move'
            code = buildRelativeMoveCode(cmd, duration);
        otherwise
            code = sprintf('error(''Unknown command: %s'');', cmd.cmd);
    end
end

function code = buildHomeCode(duration)
    code = sprintf([...
        '%% Auto-generated: home\n' ...
        'duration = %g;\n' ...
        'fig = findobj(''Type'', ''figure'', ''Name'', ''RobotAgent - 7R Arm'');\n' ...
        'if isempty(fig) || ~isvalid(fig), error(''Figure not found. Run robotagent first.''); end\n' ...
        'ud = fig.UserData;\n' ...
        'arm = ud.arm;\n' ...
        'current_q = ud.current_q;\n' ...
        'q_target = zeros(1, 7);\n' ...
        'q_traj = quinticTrajectory(current_q, q_target, duration, 30);\n' ...
        'for i = 1:size(q_traj, 1)\n' ...
        '    updateRobotFigure(fig, q_traj(i, :));\n' ...
        'drawnow;
' ...
        '    t0 = tic;
' ...
        '    while toc(t0) < 1/30, end
' ...
        'end\n' ...
        'fig.UserData.current_q = q_target;\n' ...
        'fprintf(''[Done] home (duration=%%.1fs)\\n'', duration);\n' ...
    ], duration);
end
function code = buildMoveToCode(cmd, duration)
    pos = cmd.position;
    code = sprintf([...
        '%% Auto-generated: move_to [%.4f, %.4f, %.4f]\n' ...
        'duration = %g;\n' ...
        'fig = findobj(''Type'', ''figure'', ''Name'', ''RobotAgent - 7R Arm'');\n' ...
        'if isempty(fig) || ~isvalid(fig), error(''Figure not found. Run robotagent first.''); end\n' ...
        'ud = fig.UserData;\n' ...
        'arm = ud.arm;\n' ...
        'current_q = ud.current_q;\n' ...
        'T_cur = arm.forwardKinematics(current_q);\n' ...
        'T_target = T_cur;\n' ...
        'T_target(1:3, 4) = [%f; %f; %f];\n' ...
        '[q_target, err] = arm.inverseKinematics(T_target);\n' ...
        'if err ~= 0, error(''move_to: Target unreachable''); end\n' ...
        'steps = max(30, round(duration * 30));\n' ...
        '[~, q_traj, ~] = arm.planTrajectoryCartesian(T_cur, T_target, steps, 0, duration);\n' ...
        'if any(isnan(q_traj(1, :))), q_traj(1, :) = current_q; end\n' ...
        'nan_rows = find(any(isnan(q_traj), 2));\n' ...
        'if ~isempty(nan_rows)\n' ...
        '    first_nan = nan_rows(1);\n' ...
        '    for i = 1:first_nan-1\n' ...
        '        updateRobotFigure(fig, q_traj(i, :));\n' ...
        'drawnow;
' ...
        '    t0 = tic;
' ...
        '    while toc(t0) < 1/30, end
' ...
        '    end\n' ...
        '    fig.UserData.current_q = q_traj(first_nan-1, :);\n' ...
        '    scriptDir = fileparts(mfilename(''fullpath''));
' ...
        '    pause_path = fullfile(scriptDir, ''..'', ''incoming'', sprintf(''pause_%%s.txt'', datestr(now, ''yyyymmdd_HHMMSS_FFF'')));
